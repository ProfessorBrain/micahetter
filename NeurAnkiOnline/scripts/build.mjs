// A deliberately small, dependency-free packager for this app's named-function
// modules. Keep module scopes isolated and fail on unsupported module syntax.
// The checked-in classic script works under both file:// and HTTP(S).
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(import.meta.dirname, '..');
const order = ['scheduler.js', 'renderer.js', 'study.js', 'storage.js', 'app.js'];

export async function generateBundle() {
  const modules = [];
  const packed = new Set();
  const deck = JSON.parse(await readFile(resolve(root, 'data/deck.json'), 'utf8'));
  for (const name of order) {
    let source = await readFile(resolve(root, name), 'utf8');
    const exports = [];
    source = source.replace(/^import \{([^}]+)\} from ['"]\.\/([^'"]+)['"];\r?\n/gm, (_, bindings, dependency) => {
      if (!packed.has(dependency)) throw new Error(`Dependency ${dependency} must precede ${name}`);
      return `const {${bindings}} = modules[${JSON.stringify(dependency)}];\n`;
    });
    source = source.replace(/^import deckData from '\.\/data\/deck\.json' with \{ type: 'json' \};\r?\n/m,
      // JSON.parse preserves object keys as data and does not interpret HTML.
      () => `const deckData = JSON.parse(${JSON.stringify(JSON.stringify(deck))});\n`);
    source = source.replace(/^export (async )?function (\w+)/gm, (_, asyncKeyword = '', exported) => {
      exports.push(exported);
      return `${asyncKeyword}function ${exported}`;
    });
    if (/^\s*(import|export)\s/m.test(source)) throw new Error(`Unsupported module syntax in ${name}`);
    modules.push(`// ${name}\nmodules[${JSON.stringify(name)}] = (() => {\n${source}\nreturn {${exports.join(', ')}};\n})();`);
    packed.add(name);
  }
  return `// Generated by npm run build. Edit the source modules, not this file.\n(() => {\n'use strict';\nconst modules = Object.create(null);\n${modules.join('\n\n')}\n})();\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundle = await generateBundle();
  await writeFile(resolve(root, 'app.bundle.js'), bundle);
  console.log(`Built app.bundle.js (${(Buffer.byteLength(bundle) / 1024 / 1024).toFixed(2)} MB), including the complete deck.`);
}
